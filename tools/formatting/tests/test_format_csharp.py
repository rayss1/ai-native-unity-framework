"""在真实临时 Git 工作树中验证格式检查范围，不依赖暂存或 CSharpier。"""

import importlib.util
from pathlib import Path
import subprocess
import tempfile
import unittest

SCRIPT = Path(__file__).resolve().parents[1] / "format_csharp.py"
SPEC = importlib.util.spec_from_file_location("format_csharp", SCRIPT)
formatter = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(formatter)


class SourceDiscoveryTests(unittest.TestCase):
    def setUp(self):
        self.directory = tempfile.TemporaryDirectory()
        self.addCleanup(self.directory.cleanup)
        self.root = Path(self.directory.name)
        self.git("init", "--quiet")

    def git(self, *arguments):
        return subprocess.check_output(["git", *arguments], cwd=self.root)

    def write(self, relative, content="class Example {}\n"):
        path = self.root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        return path

    def test_client_includes_tracked_and_untracked_sources_without_staging(self):
        tracked = "packages/com.ainative.client.example/Runtime/Tracked.cs"
        self.write(tracked)
        self.git("add", "--", tracked)
        new_paths = [
            "packages/com.ainative.client.example/Editor/NewEditor.cs",
            "packages/com.ainative.client.example/Tests/NewTest.cs",
            "packages/com.ainative.client.example/Samples~/Example/NewSample.cs",
            "client/UnityProject/Assets/AiNative.Example/Runtime/New Client.cs",
        ]
        for path in new_paths:
            self.write(path)
        index_before = self.git("ls-files", "--stage", "-z")
        self.assertEqual(
            formatter.discover_sources(self.root, "client"), sorted([tracked, *new_paths])
        )
        self.assertEqual(self.git("ls-files", "--stage", "-z"), index_before)
        self.assertEqual(self.git("ls-files").decode().splitlines(), [tracked])

    def test_client_excludes_other_layers_vendor_and_generated_code(self):
        excluded = [
            "shared/gameplay/Shared.cs",
            "server/src/Server.cs",
            "tools/Tool.cs",
            "packages/com.ainative.shared.example/Runtime/Shared.cs",
            "client/UnityProject/Assembly-CSharp.cs",
            "client/UnityProject/Assets/ThirdParty/Vendor.cs",
            "packages/com.ainative.client.example/vendor/Vendor.cs",
            "packages/com.ainative.client.example/ThirdParty/Vendor.cs",
        ]
        for path in excluded:
            self.write(path)
        self.write(
            "client/UnityProject/Assets/AiNative.Example/Input/CharacterControls.cs",
            "\ufeff// <auto-generated> Input System output </auto-generated>\nclass Controls {}",
        )
        self.write(
            "packages/com.ainative.client.example/Runtime/GeneratedProtocol.cs",
            "// <autogenerated> Protocol output </autogenerated>\nclass Protocol {}",
        )
        self.assertEqual(formatter.discover_sources(self.root, "client"), [])

    def test_git_ignore_is_respected_and_deleted_tracked_sources_are_skipped(self):
        self.write(".gitignore", "**/Ignored.cs\n")
        self.write("packages/com.ainative.client.example/Runtime/Ignored.cs")
        deleted = "packages/com.ainative.client.example/Runtime/Deleted.cs"
        path = self.write(deleted)
        self.git("add", "--", deleted)
        path.unlink()
        kept = "packages/com.ainative.client.example/Runtime/Kept.cs"
        self.write(kept)
        self.assertEqual(formatter.discover_sources(self.root, "client"), [kept])

    def test_all_scope_keeps_owned_other_layers_but_excludes_generated_protocol(self):
        owned = ["shared/gameplay/Gameplay.cs", "server/src/Server.cs"]
        for path in owned:
            self.write(path)
        self.write("shared/generated/csharp/Protocol.cs")
        self.assertEqual(formatter.discover_sources(self.root), sorted(owned))
        with self.assertRaises(ValueError):
            formatter.discover_sources(self.root, "unknown")


if __name__ == "__main__":
    unittest.main()
