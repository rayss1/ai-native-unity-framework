#!/usr/bin/env python3
"""Format tracked project-owned C# sources with the pinned local CSharpier tool."""

import argparse
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check without writing files.")
    args = parser.parse_args()
    paths = (
        subprocess.check_output(["git", "ls-files", "-z", "--", "*.cs"], cwd=ROOT)
        .decode("utf-8")
        .split("\0")
    )
    sources = []
    for relative in filter(None, paths):
        path = ROOT / relative
        if (
            "vendor" in path.parts
            or "ThirdParty" in path.parts
            or relative.startswith("shared/generated/")
            or not path.is_file()
        ):
            continue
        header = path.read_text(encoding="utf-8-sig")[:1500].lower()
        if "<auto-generated" in header or "<autogenerated" in header:
            continue
        sources.append(relative)

    command = "check" if args.check else "format"
    for start in range(0, len(sources), 40):
        subprocess.run(
            ["dotnet", "csharpier", command, *sources[start : start + 40]],
            cwd=ROOT,
            check=True,
        )
    print(f"{command}: {len(sources)} project-owned C# files")


if __name__ == "__main__":
    main()
